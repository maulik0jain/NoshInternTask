"""Compile experiments/LOG.md (and experiments/log.json for the report) from the
trial configs (what / why / decision / reason, written by hand) and their
results.json (numbers, written only by run_experiment.py). Numbers are never typed.

    python scripts/build_log.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import yaml  # noqa: E402

EXP = ROOT / "experiments"
# dataviz reference palette (light): slot 1 for kept trials, muted ink for discarded ones
KEPT, DROPPED, INK2, GRID, SURFACE = "#2a78d6", "#b9b8b3", "#52514e", "#e4e3df", "#fcfcfb"


def trial_order(d):
    m = re.match(r"T(\d+)([a-z]?)$", d.name)
    return (int(m[1]), m[2]) if m else (999, d.name)


def fmt(x, nd=3):
    return "-" if x is None else f"{x:.{nd}f}"


def plot_progress(trials, path, title="Dev IoU per trial (run order)"):
    """Dev mean IoU of every trial in run order; discarded trials greyed out. A dashed
    line marks where round 2 starts, if the list spans both rounds."""
    fig, ax = plt.subplots(figsize=(7.4 if len(trials) <= 16 else 9.6, 2.7), dpi=150, facecolor=SURFACE)
    ax.set_facecolor(SURFACE)
    x = range(len(trials))
    colors = [DROPPED if t["decision"] == "discarded" else KEPT for t in trials]
    ax.bar(x, [t["iou"] for t in trials], width=0.72, color=colors)
    for i, t in enumerate(trials):
        ax.text(i, t["iou"] + 0.012, f"{t['iou']:.2f}", ha="center", fontsize=7, color=INK2)
    ax.set_xticks(list(x), [t["id"] for t in trials], fontsize=8, color=INK2)
    ax.set_ylim(0, 0.7)
    ax.set_ylabel("dev mean IoU", color=INK2, fontsize=8.5)
    ax.tick_params(axis="y", labelsize=8, colors=INK2)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.bar([0], [0], color=KEPT, label="kept (T0 = baseline)")
    ax.bar([0], [0], color=DROPPED, label="discarded")
    ax.legend(loc="upper left", frameon=False, fontsize=8)
    r2 = [i for i, t in enumerate(trials) if t["round"] == 2]
    if r2 and r2[0] > 0:
        ax.set_ylim(0, 0.8)  # headroom so the round label clears the value labels
        ax.axvline(r2[0] - 0.5, color=INK2, linewidth=0.8, linestyle="--")
        ax.text(r2[0] - 0.4, 0.74, "round 2 →", fontsize=8, color=INK2)
    ax.set_title(title, fontsize=10, fontweight="bold", loc="left")
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def main():
    trials = []
    for d in sorted((p for p in EXP.iterdir() if p.is_dir() and re.match(r"T\d+", p.name)), key=trial_order):
        cfg = yaml.safe_load((d / "config.yaml").read_text())
        res = json.loads((d / "results.json").read_text())["summary"]
        trials.append({"id": cfg["id"], "round": cfg.get("round", 1), "extends": cfg["extends"],
                       "what": cfg["what"], "why": cfg["why"],
                       "changes": cfg.get("changes") or {}, "decision": cfg.get("decision", "?"),
                       "reason": cfg.get("reason", ""),
                       "iou": res["iou"]["mean"], "iou_med": res["iou"]["median"], "dice": res["dice"]["mean"],
                       "precision": res["precision"]["mean"], "recall": res["recall"]["mean"],
                       "bf1": res["boundary_f1"]["mean"], "inst_f1": res["instance"]["f1"],
                       "empty": res["empty_predictions"]})
    sweeps = [json.loads(p.read_text()) | {"name": p.stem} for p in sorted((EXP / "sweeps").glob("*.json"))]

    lines = ["# Experiment log (Task 2)", "",
             "All numbers: DEV split (85 images), pseudo-GT from Task 1. Eval was not used for any decision.",
             "Decision rule: keep a change if dev mean IoU goes up; if IoU ties, keep it only if another metric "
             "improves (boundary F1 / instance F1). Generated by `scripts/build_log.py` - do not edit by hand.", "",
             "| Trial | Change | IoU mean | IoU median | Precision | Recall | Boundary F1 | Instance F1 | Empty | Decision |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for t in trials:
        lines.append(f"| {t['id']} | {t['what']} | {fmt(t['iou'])} | {fmt(t['iou_med'])} | {fmt(t['precision'])} | "
                     f"{fmt(t['recall'])} | {fmt(t['bf1'])} | {fmt(t['inst_f1'])} | {t['empty']} | {t['decision']} |")
    lines += ["", "## Trials", ""]
    for t in trials:
        lines += [f"### {t['id']} - {t['what']}", "",
                  f"- **Builds on:** {t['extends']}",
                  f"- **Why:** {t['why']}",
                  f"- **Params changed:** `{json.dumps(t['changes'])}`",
                  f"- **Dev:** IoU {fmt(t['iou'])} (median {fmt(t['iou_med'])}), Dice {fmt(t['dice'])}, "
                  f"P {fmt(t['precision'])}, R {fmt(t['recall'])}, BF1 {fmt(t['bf1'])}, "
                  f"instance F1 {fmt(t['inst_f1'])}, empty masks {t['empty']}",
                  f"- **Decision:** {t['decision']} - {t['reason']}", ""]
    lines += ["## Parameter sweeps (dev)", ""]
    for s in sweeps:
        lines += [f"### {s['name']}: `{s['param']}` on top of {s['base']}", "",
                  "| Value | IoU mean | IoU median | Boundary F1 | Instance F1 | Empty |", "|---|---|---|---|---|---|"]
        for r in s["runs"]:
            lines.append(f"| {json.dumps(r['value'])} | {fmt(r['iou_mean'])} | {fmt(r['iou_median'])} | "
                         f"{fmt(r['boundary_f1'])} | {fmt(r['instance_f1'])} | {r['empty']} |")
        lines.append("")
    (EXP / "LOG.md").write_text("\n".join(lines), encoding="utf-8")
    (EXP / "log.json").write_text(json.dumps({"trials": trials, "sweeps": sweeps}, indent=2))
    plot_progress([t for t in trials if t["round"] == 1], EXP / "progress.png")
    if any(t["round"] == 2 for t in trials):
        plot_progress(trials, EXP / "progress_all.png", "Dev IoU per trial, both rounds (run order)")
    print(f"{len(trials)} trials, {len(sweeps)} sweeps -> experiments/LOG.md")


if __name__ == "__main__":
    main()
